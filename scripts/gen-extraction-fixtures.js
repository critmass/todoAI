#!/usr/bin/env node
// Generates src/dev/extractionFixturesData.ts from docs/eval/extraction_fixtures_seed.jsonl.
//
// Why: Metro cannot import .jsonl into the RN bundle, but the Task 7 on-device tuning harness
// needs the seed fixtures AND their `gold` values (the correctness oracle). Hand-transcribing an
// oracle is how you get a scorer that lies, so this is mechanical and re-runnable. Same convention
// as src/llm/grammar/grammarText.ts: regenerate, never hand-edit.
//
// Usage: node scripts/gen-extraction-fixtures.js

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'docs/eval/extraction_fixtures_seed.jsonl');
const OUT = path.join(ROOT, 'src/dev/extractionFixturesData.ts');

const lines = fs
  .readFileSync(SRC, 'utf-8')
  .split('\n')
  .map((l) => l.trim())
  .filter((l) => l.length > 0);

const fixtures = lines.map((l, i) => {
  try {
    return JSON.parse(l);
  } catch (err) {
    throw new Error(`line ${i + 1} is not valid JSON: ${err.message}`);
  }
});

const header = `// AUTO-GENERATED by scripts/gen-extraction-fixtures.js — do not hand-edit.
// Source of truth: docs/eval/extraction_fixtures_seed.jsonl (${fixtures.length} fixtures).
// Metro can't import .jsonl, and the Task 7 tuning harness needs the fixtures + their \`gold\`
// correctness oracle on-device. Regenerate, never patch.

import type { ExtractionFixture } from './extractionScoring';

export const EXTRACTION_FIXTURES: ExtractionFixture[] = ${JSON.stringify(fixtures, null, 2)};
`;

fs.writeFileSync(OUT, header, 'utf-8');
console.log(`wrote ${OUT} (${fixtures.length} fixtures)`);
