#!/usr/bin/env node
/* eslint-env node */
/**
 * Task 44, item 5 — "purge junk-tags and all other junk data" (Jason, 2026-08-18).
 *
 * THE MECHANISM. `tagKnown` (the extraction grammar's known-tag alternation,
 * src/llm/grammar/grammarText.ts) is built from every tag the app already holds
 * (chatController.ts's `contextTagVocabulary`), so any junk tag already persisted keeps being
 * offered back to the model as a legitimate known tag — FOREVER, regardless of any grammar fix,
 * because a grammar fix only stops NEW junk from being generated; it cannot clean what is already
 * stored (task 37 findings report §5). This script is the data pass task 37 says is owed.
 *
 * THE DEFINITION OF "JUNK" USED HERE, STATED EXPLICITLY AND KEPT DELIBERATELY NARROW:
 *
 *   An entry in `tasks.context_tags` or `tasks.tool_requirements` whose FIRST CHARACTER is not
 *   alphanumeric ([a-zA-Z0-9]).
 *
 * This is not a heuristic — it is the EXACT character class task 37's grammar fix now forbids at
 * the source (`firstChar ::= [a-zA-Z0-9]` in every free-text rule, including `newTag`, in all four
 * .gbnf files). A tag/tool that fails this test could not be generated by the current grammar; it
 * can only be a survivor from before the fix — exactly the `":mixing"` / `":episode"` class task 37
 * confirmed as a leading-separator artifact of the OLD `newTag ::= "\"" jchar{1,20} "\""` rule.
 *
 * WHAT THIS DELIBERATELY DOES NOT TOUCH, AND WHY (task 44 brief §"Item 5", ⚠ conservative-by-design):
 *
 *   - `"work_on_it_until_did"`-class tags. Task 37's own findings report is explicit that this is a
 *     DIFFERENT root cause — a phrasing failure (a snake_case sentence fragment), not a grammar
 *     hole — and it begins with an alphanumeric character, so the firstChar rule never touched it
 *     and never will. It is flagged in orientation's standing notes as a TRACKED SIGNAL deliberately
 *     left alone, not a bug. This script does not attempt to detect "looks like a sentence, not a
 *     tag" — that is a judgment call, not a grammar fact, and sweeping it in here would be exactly
 *     the over-deletion the brief warns against ("over-deleting is worse than under-deleting: this
 *     is his real alpha data").
 *   - Anything outside `context_tags`/`tool_requirements`. `tagKnown`'s vocabulary is drawn from
 *     these two columns only (context_tags feeds `context_tags_known`; tool_requirements has its
 *     own `tool` rule with the identical firstChar-guarded shape). No other column is a candidate
 *     "known" vocabulary fed back to the model, so no other column is in scope for THIS defect.
 *   - Anything whose first character IS alphanumeric but whose CONTENT still looks wrong (a typo,
 *     an overly long tag, an inconsistent capitalisation). Ambiguous cases are not deleted — if you
 *     spot one while reading the dry-run report, it is not this script's junk, and it stays.
 *
 * USAGE (dry-run is the default — nothing is ever written without --apply):
 *
 *   node scripts/purge-junk-tags.js --db <path/to/todoai.db>              # report only
 *   node scripts/purge-junk-tags.js --db <path/to/todoai.db> --apply      # actually purge
 *
 * IDEMPOTENT BY CONSTRUCTION. The purge only ever REMOVES entries matching the rule above; running
 * it again against an already-purged database finds nothing left to remove (every remaining tag/
 * tool starts with an alphanumeric character by definition) and reports zero changes. It never
 * touches a task whose arrays contain no junk, and it writes back the FULL cleaned array in one
 * UPDATE per affected task — never a partial write, never a second matcher re-deriving the rule.
 *
 * 🔴 BACK UP FIRST. `--apply` performs real DELETEs-in-place (array-element removal via UPDATE) on
 * Jason's actual alpha data. Task 14 Phase A landed a working VACUUM INTO backup
 * (`src/services/backup/`) but it is DELIBERATELY NOT WIRED into the app (task 14 report §13) — this
 * script does not wire it either; that is not this task's job. Take a manual copy of the working
 * database file before running with --apply. This script does not check for one and will not refuse
 * to run without one — it only reminds you, loudly, below.
 */

const path = require('path');

/** The exact rule task 37's grammar now enforces at generation time (`firstChar ::= [a-zA-Z0-9]`
 *  in src/llm/grammar/grammarText.ts, all four .gbnf files). Kept as one small function so the
 *  definition of "junk" lives in exactly one place in this script. */
function isJunkTag(value) {
  return typeof value === 'string' && value.length > 0 && !/^[a-zA-Z0-9]/.test(value);
}

/** Parses a `tasks.context_tags` / `tasks.tool_requirements` JSON column. Returns `null` (not `[]`)
 *  on anything that isn't a clean JSON array of strings, so the caller can report it for manual
 *  review rather than silently coercing malformed data into an empty array (which would be a
 *  DELETION of unknown content by another name). */
function parseTagArray(raw) {
  if (raw == null) return [];
  try {
    const parsed = JSON.parse(raw);
    if (!Array.isArray(parsed) || !parsed.every((entry) => typeof entry === 'string')) return null;
    return parsed;
  } catch {
    return null;
  }
}

/**
 * Scans every task row (any status — soft-deleted and completed tasks are real history that may
 * still be read, so junk there is still junk) for junk entries in the two columns. Returns a
 * report; makes NO writes.
 */
function scanDatabase(db) {
  const rows = db
    .prepare('SELECT id, title, status, context_tags, tool_requirements FROM tasks ORDER BY id')
    .all();

  const findings = [];
  const unparseable = [];

  for (const row of rows) {
    for (const column of ['context_tags', 'tool_requirements']) {
      const parsed = parseTagArray(row[column]);
      if (parsed === null) {
        unparseable.push({ taskId: row.id, title: row.title, column, raw: row[column] });
        continue;
      }
      const junk = parsed.filter(isJunkTag);
      if (junk.length > 0) {
        findings.push({ taskId: row.id, title: row.title, status: row.status, column, junk, kept: parsed.filter((v) => !isJunkTag(v)) });
      }
    }
  }

  const junkCounts = new Map();
  for (const finding of findings) {
    for (const value of finding.junk) junkCounts.set(value, (junkCounts.get(value) ?? 0) + 1);
  }

  return {
    tasksScanned: rows.length,
    findings,
    unparseable,
    junkCounts,
    totalJunkEntries: findings.reduce((sum, f) => sum + f.junk.length, 0),
  };
}

/** Applies the removal found by `scanDatabase` in one transaction, one UPDATE per affected task
 *  (both columns folded into the same statement when a task has junk in both). Returns the same
 *  shape as `scanDatabase` (re-scans first) plus `applied: true`. */
function purgeDatabase(db) {
  const report = scanDatabase(db);
  const byTask = new Map();
  for (const finding of report.findings) {
    const entry = byTask.get(finding.taskId) ?? {};
    entry[finding.column] = finding.kept;
    byTask.set(finding.taskId, entry);
  }

  const update = db.prepare(
    'UPDATE tasks SET context_tags = COALESCE(?, context_tags), tool_requirements = COALESCE(?, tool_requirements) WHERE id = ?',
  );
  const applyAll = db.transaction((entries) => {
    for (const [taskId, patch] of entries) {
      update.run(
        patch.context_tags !== undefined ? JSON.stringify(patch.context_tags) : null,
        patch.tool_requirements !== undefined ? JSON.stringify(patch.tool_requirements) : null,
        taskId,
      );
    }
  });
  applyAll([...byTask.entries()]);

  return { ...report, applied: true, tasksUpdated: byTask.size };
}

function formatReport(report, mode) {
  const lines = [];
  lines.push(`purge-junk-tags — ${mode}`);
  lines.push(`tasks scanned: ${report.tasksScanned}`);
  lines.push(`junk entries found: ${report.totalJunkEntries} across ${report.findings.length} task/column pair(s)`);
  lines.push('');
  if (report.findings.length === 0) {
    lines.push('nothing to do — no leading-separator junk found (or already purged).');
  } else {
    for (const finding of report.findings) {
      lines.push(
        `  task #${finding.taskId} "${finding.title}" [${finding.status}] .${finding.column}: ` +
          `${JSON.stringify(finding.junk)} ${mode === 'apply' ? 'REMOVED' : 'would be removed'}`,
      );
    }
    lines.push('');
    lines.push('by value:');
    for (const [value, count] of [...report.junkCounts.entries()].sort((a, b) => b[1] - a[1])) {
      lines.push(`  ${JSON.stringify(value)}  ×${count}`);
    }
  }
  if (report.unparseable.length > 0) {
    lines.push('');
    lines.push('UNPARSEABLE (not touched — list for manual review, not auto-deleted):');
    for (const entry of report.unparseable) {
      lines.push(`  task #${entry.taskId} "${entry.title}" .${entry.column}: ${entry.raw}`);
    }
  }
  return lines.join('\n');
}

function parseArgs(argv) {
  const args = { db: null, apply: false };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === '--db') args.db = argv[++i];
    else if (arg === '--apply') args.apply = true;
    else if (arg === '--help' || arg === '-h') args.help = true;
  }
  return args;
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  if (args.help || !args.db) {
    process.stdout.write(
      'Usage: node scripts/purge-junk-tags.js --db <path/to/todoai.db> [--apply]\n\n' +
        'Dry-run (report only) unless --apply is passed. See this file\'s header for the exact\n' +
        'definition of "junk" used and what is deliberately left alone.\n',
    );
    process.exitCode = args.help ? 0 : 1;
    return;
  }

  // Lazy require: this script must still print --help without better-sqlite3 present (e.g. a
  // fresh checkout that hasn't run `npm install` for native deps yet), matching pull-capture.js's
  // own lazy-require discipline.
  const Database = require('better-sqlite3');
  const dbPath = path.resolve(args.db);
  const db = new Database(dbPath);
  try {
    if (!args.apply) {
      const report = scanDatabase(db);
      process.stdout.write(formatReport(report, 'dry-run') + '\n');
      if (report.findings.length > 0) {
        process.stdout.write(
          '\nRe-run with --apply to remove the entries listed above.\n' +
            '🔴 Take a backup of the working database file first — this is real alpha data and the\n' +
            'app-level backup (src/services/backup/) is deliberately not wired in to do this for you.\n',
        );
      }
    } else {
      process.stdout.write(
        '🔴 About to modify the database in place. If you have not already backed it up, stop now\n' +
          'and copy the working database file before continuing.\n\n',
      );
      const report = purgeDatabase(db);
      process.stdout.write(formatReport(report, 'apply') + '\n');
      process.stdout.write(`\n${report.tasksUpdated} task row(s) updated.\n`);
    }
  } finally {
    db.close();
  }
}

if (require.main === module) main();

module.exports = { isJunkTag, parseTagArray, scanDatabase, purgeDatabase, formatReport, parseArgs };
