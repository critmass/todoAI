#!/usr/bin/env node
/**
 * Regenerate docs/master_task_table.html from docs/master_task_table.md.
 *
 *   node scripts/gen-task-table.js
 *
 * The markdown is the source of truth. Never hand-edit the HTML — it is
 * overwritten. The stylesheet lives at the bottom of this file so the whole
 * renderer is one committed artifact with no dependencies.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'docs', 'master_task_table.md');
const OUT = path.join(ROOT, 'docs', 'master_task_table.html');

const LABELS = ['#', 'Status', 'Task', 'Description', 'Dep', 'Model'];

const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

function inline(s) {
  s = esc(s).replace(/\\\|/g, '|');
  s = s.replace(/`([^`]+)`/g, '<code>$1</code>');
  s = s.replace(/\*\*\*(.+?)\*\*\*/g, '<strong><em>$1</em></strong>');
  s = s.replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>');
  s = s.replace(/~~(.+?)~~/g, '<s>$1</s>');
  s = s.replace(/(^|[^\w*])\*([^*\n]+?)\*(?![\w*])/g, '$1<em>$2</em>');
  s = s.replace(/🔴\s*/g, '<span class="gate">🔴 </span>');
  return s;
}

const devBadge = (s) => s.replace(/<strong>P<\/strong>/g, '<span class="dev">P</span>');

function pill(raw) {
  const t = raw.replace(/\*/g, '').trim();
  if (/CRITICAL/.test(t)) return '<span class="pill p-crit">Critical path</span>';
  if (t.startsWith('—')) return '<span class="pill p-res">Reserved</span>';
  if (/Done/.test(t)) {
    const m = t.match(/\((merged[^)]*)\)/);
    const note = m
      ? `<em style="display:block;font-size:11px;color:var(--ink-faint);margin-top:3px">${inline(m[1])}</em>`
      : '';
    return `<span class="pill p-done">Done</span>${note}`;
  }
  if (/Partial/.test(t)) return '<span class="pill p-partial">Partial</span>';
  if (/🔴/.test(raw)) return '<span class="pill p-undone">Undone</span> <span class="gate">🔴</span>';
  return '<span class="pill p-undone">Undone</span>';
}

function splitRow(line) {
  const cells = [];
  let cur = '';
  let esc_ = false;
  for (const ch of line.trim().replace(/^\||\|$/g, '')) {
    if (esc_) { cur += ch; esc_ = false; continue; }
    if (ch === '\\') { cur += ch; esc_ = true; continue; }
    if (ch === '|') { cells.push(cur); cur = ''; } else cur += ch;
  }
  cells.push(cur);
  return cells.map((c) => c.trim());
}

const md = fs.readFileSync(SRC, 'utf8').split('\n');
const out = [];
out.push('<!DOCTYPE html>', '<html lang="en">', '<head>', '<meta charset="utf-8">',
  '<meta name="viewport" content="width=device-width, initial-scale=1">',
  '<title>todoAI — Master Task Table</title>',
  '<!-- GENERATED by scripts/gen-task-table.js from docs/master_task_table.md — do not hand-edit -->',
  STYLE(), '</head>', '<body>', '');

for (let i = 0; i < md.length;) {
  const s = md[i].trim();

  if (s.startsWith('# ')) { out.push(`<h1>${inline(s.slice(2))}</h1>`); i++; continue; }
  if (s.startsWith('## ')) { out.push(`<h2>${inline(s.slice(3))}</h2>`); i++; continue; }

  if (s.startsWith('> ###')) {
    const body = [];
    while (i < md.length && md[i].startsWith('>')) {
      const t = md[i].replace(/^>+/, '').trim();
      if (t) body.push(t);
      i++;
    }
    out.push('<div class="warnbox">', `<h3>${inline(body[0].replace(/^#+\s*/, ''))}</h3>`);
    body.slice(1).forEach((p) => out.push(`<p>${inline(p)}</p>`));
    out.push('</div>');
    continue;
  }

  if (s === '---') { i++; continue; }

  if (s.startsWith('|')) {
    const header = splitRow(md[i]);
    i += 2; // skip the --- separator row
    const rows = [];
    while (i < md.length && md[i].trim().startsWith('|')) rows.push(splitRow(md[i++]));
    const isTaskTable = header[0] === '#' && header.length === 6;

    if (isTaskTable) {
      // Every task row must split into exactly 6 cells. A stray or missing
      // unescaped `|` (literal pipes in content must be written `\|`) yields a
      // mis-celled row: too few crashes the render, too many silently shifts
      // Dep/Model into the wrong columns. Fail loud rather than emit a wrong
      // board -- this has bitten repeatedly. (Row 0 is the `#`/Status/... header
      // already consumed as `header`; `rows` are the data rows only.)
      for (const r of rows) {
        if (r.length !== 6) {
          console.error(
            `MALFORMED task row: got ${r.length} cells, expected 6 (id "${(r[0] || '').trim()}").\n` +
            `A literal | in a cell must be escaped as \\|. Cells: ${JSON.stringify(r.map((c) => c.slice(0, 20)))}`
          );
          process.exit(1);
        }
      }
      out.push('<table>',
        '<colgroup><col class="c-num"><col class="c-stat"><col class="c-task">' +
        '<col class="c-desc"><col class="c-dep"><col class="c-model"></colgroup>',
        '<thead><tr>' + LABELS.map((h) => `<th>${h}</th>`).join('') + '</tr></thead>', '<tbody>');
      for (const r of rows) {
        out.push(
          `<tr><td class="num">${inline(r[0].replace(/\*/g, '').trim())}</td>` +
          `<td data-lbl="Status">${pill(r[1])}</td>`,
          `<td class="task" data-lbl="Task">${inline(r[2])}</td>`,
          `<td class="desc" data-lbl="Description">${inline(r[3])}</td>`,
          `<td class="dep" data-lbl="Dep">${devBadge(inline(r[4]))}</td>` +
          `<td class="model" data-lbl="Model">${inline(r[5])}</td></tr>`, '');
      }
      out.push('</tbody>', '</table>', '');
    } else {
      out.push('<table class="plain">', '<thead><tr>' +
        header.map((h) => `<th>${inline(h)}</th>`).join('') + '</tr></thead>', '<tbody>');
      rows.forEach((r) => out.push('<tr>' + r.map((c) => `<td>${inline(c)}</td>`).join('') + '</tr>'));
      out.push('</tbody>', '</table>', '');
    }
    continue;
  }

  if (s.startsWith('- ')) {
    out.push('<ul>');
    while (i < md.length && md[i].trim().startsWith('- ')) out.push(`<li>${inline(md[i++].trim().slice(2))}</li>`);
    out.push('</ul>');
    continue;
  }

  if (s) out.push(`<p class="body">${devBadge(inline(s))}</p>`);
  i++;
}

out.push('', '</body>', '</html>', '');
const html = out.join('\n');

// --check renders in-memory and compares to the committed HTML WITHOUT writing,
// exiting non-zero if they differ. This is the drift guard: the markdown is the
// source of truth and the HTML is generated, so a commit that edits the markdown
// without regenerating leaves the two disagreeing — the exact failure this repo
// keeps paying for. `scripts/__tests__/gen-task-table.test.js` runs this in the
// suite so drift fails loudly instead of shipping silently.
if (process.argv.includes('--check')) {
  const existing = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (existing !== html) {
    console.error(
      `STALE: ${path.relative(ROOT, OUT)} does not match ${path.relative(ROOT, SRC)}.\n` +
      `Run: node scripts/gen-task-table.js`
    );
    process.exit(1);
  }
  console.log(`in sync: ${path.relative(ROOT, OUT)} matches the markdown`);
} else {
  fs.writeFileSync(OUT, html, 'utf8');
  console.log(`wrote ${path.relative(ROOT, OUT)} (${html.length} bytes) from ${path.relative(ROOT, SRC)}`);
}

