// Task 41 — SHA-256, because `modelio.grammarSha8` has to be a real SHA-256 prefix.
//
// WHY NOT A CHEAPER HASH. The field's entire job is to answer "which grammar text was actually
// handed to llama.cpp on this call" — pre- or post-task-37, released or locally edited — and the
// way anyone answers it is `sha256sum src/llm/extraction/task_extraction.v1.gbnf` on the host and
// a string compare. An FNV or djb2 digest under a field named `grammarSha8` would be a false
// statement written into a permanent record, and the record is the only thing task 31 and task 40
// will have. React Native has no `crypto.subtle` and no Node `crypto`, so it is implemented here.
//
// COST: ~5 KB of grammar per constrained call, and results are memoised by the grammar text, so
// in practice this runs a handful of times per process rather than per call.

